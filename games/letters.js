// Handwriting strokes for the English alphabet, in the order and direction children are taught to write them.
// Units: y points down; capitals are 0..100 tall; lowercase has x-height 45..100, ascenders from 0, descenders to 135.
// Each letter is a list of strokes (one stroke = one continuous finger movement); each stroke is a list of [x, y] points.

const L = (...p) => { const out = []; for (let i = 0; i < p.length; i += 2) out.push([p[i], p[i + 1]]); return out; };
// arc from angle a0 to a1 (degrees; 0 = right, 90 = down, so increasing angles go clockwise on screen)
const A = (cx, cy, rx, ry, a0, a1) => {
  const n = Math.max(6, Math.ceil(Math.abs(a1 - a0) / 10)), out = [];
  for (let k = 0; k <= n; k++) { const a = (a0 + (a1 - a0) * k / n) * Math.PI / 180; out.push([cx + Math.cos(a) * rx, cy + Math.sin(a) * ry]); }
  return out;
};
const J = (...parts) => parts.flat(); // join parts into one continuous stroke

